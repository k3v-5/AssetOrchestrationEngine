class MasterPackageIntegrator:
    """
    Takes an IntegratedSliceManifest and serializes all artifacts into a structured,
    portable directory bundle with an automated UE5 reconstruction script.
    """

    def __init__(self, default_output_root: Optional[str] = None) -> None:
        self.default_output_root = default_output_root or os.path.abspath("output/slices")

    @staticmethod
    def _compute_sha256(filepath: str) -> str:
        hasher = hashlib.sha256()
        with open(filepath, "rb") as f:
            while chunk := f.read(65536):
                hasher.update(chunk)
        return hasher.hexdigest()

    def generate_ue5_automation_script(
        self,
        manifest: IntegratedSliceManifest,
        script_output_path: str,
    ) -> str:
        """
        Generates a standalone Python automation script to import and assemble
        the complete vertical slice inside Unreal Engine 5.
        """
        slice_name = manifest.slice_name
        pad_center = manifest.spatial_footprint.center_world_cm
        airlock_pos = manifest.spatial_footprint.entrance_airlock_cm
        weather_info = manifest.weather_summary
        sun_elev = weather_info.get("sun_elevation_deg", 45.0)
        sun_lux = weather_info.get("sun_lux", 75000.0)
        sun_kelvin = weather_info.get("sun_kelvin", 5500.0)
        biome = weather_info.get("biome", "TEMPERATE_FOREST")
        rt60 = manifest.audio_summary.get("bunker_rt60_seconds", 2.0)
        stems = manifest.audio_summary.get("active_stems", [])
        pieces_count = manifest.chaos_summary.get("total_fracture_pieces", 16)

        rendered = UE5_SCRIPT_TEMPLATE.format(
            slice_name=slice_name,
            pad_center_x=pad_center[0],
            pad_center_y=pad_center[1],
            pad_center_z=pad_center[2],
            airlock_pos_x=airlock_pos[0],
            airlock_pos_y=airlock_pos[1],
            airlock_pos_z=airlock_pos[2],
            biome=biome,
            sun_elev=sun_elev,
            sun_lux=sun_lux,
            sun_kelvin=sun_kelvin,
            pieces_count=pieces_count,
            rt60=rt60,
            stems=stems,
        )

        os.makedirs(os.path.dirname(script_output_path), exist_ok=True)
        with open(script_output_path, "w", encoding="utf-8") as f:
            f.write(rendered)
        return script_output_path

    def package_slice(
        self,
        manifest: IntegratedSliceManifest,
        output_dir: Optional[str] = None,
        as_zip: bool = False,
    ) -> PackageResult:
        """
        Packages all slice assets and manifests into the specified output directory.
        """
        target_dir = output_dir or os.path.join(self.default_output_root, manifest.slice_name)
        os.makedirs(target_dir, exist_ok=True)

        terrain_dir = os.path.join(target_dir, "terrain")
        spatial_dir = os.path.join(target_dir, "spatial")
        interior_dir = os.path.join(target_dir, "interior")
        ai_dir = os.path.join(target_dir, "ai")
        weather_dir = os.path.join(target_dir, "weather")
        chaos_dir = os.path.join(target_dir, "chaos")
        audio_dir = os.path.join(target_dir, "audio")
        qa_dir = os.path.join(target_dir, "qa")
        scripts_dir = os.path.join(target_dir, "scripts")

        for d in (terrain_dir, spatial_dir, interior_dir, ai_dir, weather_dir, chaos_dir, audio_dir, qa_dir, scripts_dir):
            os.makedirs(d, exist_ok=True)

        files_written: List[str] = []

        # 1. Master manifest
        manifest_path = os.path.join(target_dir, "slice_manifest.json")
        with open(manifest_path, "w", encoding="utf-8") as f:
            f.write(manifest.model_dump_json(indent=2))
        files_written.append(manifest_path)

        # 2. Heightfield binary (.r16) - 16-bit unsigned little-endian raw heightmap
        res = manifest.landscape_summary.get("resolution", 64)
        hf_path = os.path.join(terrain_dir, "heightfield.r16")
        raw_bytes = bytearray(res * res * 2)
        for i in range(res * res):
            val = int(32768 + 10000 * math.sin(i / 10.0)) & 0xFFFF
            raw_bytes[i*2] = val & 0xFF
            raw_bytes[i*2 + 1] = (val >> 8) & 0xFF
        with open(hf_path, "wb") as f:
            f.write(raw_bytes)
        files_written.append(hf_path)

        # 3. Subsystem manifests
        subsystems = [
            (terrain_dir, "landscape_weightmaps.json", manifest.landscape_summary),
            (spatial_dir, "facility_placement.json", manifest.spatial_footprint.model_dump()),
            (interior_dir, "wfc_interior.json", manifest.interior_summary),
            (ai_dir, "ai_squads.json", manifest.ai_summary),
            (weather_dir, "weather_manifest.json", manifest.weather_summary),
            (chaos_dir, "chaos_destruction.json", manifest.chaos_summary),
            (audio_dir, "metasounds_manifest.json", manifest.audio_summary),
            (qa_dir, "qa_playtest_report.json", manifest.qa_summary),
        ]

        for folder, fname, data in subsystems:
            fpath = os.path.join(folder, fname)
            with open(fpath, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2)
            files_written.append(fpath)

        # 4. UE5 Reconstruction Automation Script
        script_path = os.path.join(scripts_dir, "import_full_vertical_slice.py")
        self.generate_ue5_automation_script(manifest, script_path)
        files_written.append(script_path)

        # Calculate total bytes and checksum
        total_bytes = sum(os.path.getsize(f) for f in files_written)
        manifest_checksum = self._compute_sha256(manifest_path)

        zip_path = None
        if as_zip:
            zip_dest = target_dir.rstrip("/\\") + ".zip"
            with zipfile.ZipFile(zip_dest, "w", zipfile.ZIP_DEFLATED) as zf:
                for file_path in files_written:
                    arcname = os.path.relpath(file_path, os.path.dirname(target_dir))
                    zf.write(file_path, arcname)
            zip_path = zip_dest

        return PackageResult(
            bundle_directory=target_dir,
            files_written=files_written,
            total_bytes=total_bytes,
            manifest_checksum=manifest_checksum,
            ue5_script_path=script_path,
            is_zip=as_zip,
            zip_path=zip_path,
        )
