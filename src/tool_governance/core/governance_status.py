    READ_SCENE = "READ_SCENE"
    CREATE_ASSET = "CREATE_ASSET"
    MODIFY_ASSET = "MODIFY_ASSET"
    DELETE_ASSET = "DELETE_ASSET"
    REBUILD_ASSET = "REBUILD_ASSET"
    MODIFY_MATERIAL = "MODIFY_MATERIAL"
    MASS_OPERATION = "MASS_OPERATION"

